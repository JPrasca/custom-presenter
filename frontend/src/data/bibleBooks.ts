export type BibleCategory =
  | 'pentateuco'
  | 'historicos'
  | 'poeticos'
  | 'profetas-mayores'
  | 'profetas-menores'
  | 'evangelios'
  | 'hechos'
  | 'paulinas'
  | 'generales'
  | 'apocalipsis';

export interface CanonicalBibleBook {
  number: number;
  name: string;
  abbr: string;
  chapters: number;
  testament: 'AT' | 'NT';
  category: BibleCategory;
}

export function normalizeBookText(value: string): string {
  return value
    .normalize('NFD')
    .replaceAll(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .trim();
}

